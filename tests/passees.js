const { chromium } = require('playwright'); const fs = require('fs');
(async () => {
  const b = await chromium.launch(); const data = JSON.parse(fs.readFileSync('/tmp/demo.json', 'utf8')); const errs = [];
  data.config.ventes.liste.vold = { nom: 'Vente Collections Juin 2026', date: '2026-06-10' };
  data.config.ventes.liste.vold2 = { nom: 'Vente Single Lots Septembre 2026', date: '2026-09-20' };
  data.visites.e.vente = 'vold';
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
  await ctx.route('**/*', r => { const u = r.request().url();
    if (u.includes('firebase-app-compat')) return r.fulfill({ contentType: 'text/javascript', body: fs.readFileSync('tests/fake-firebase.js', 'utf8') });
    if (u.includes('firebase-firestore-compat')) return r.fulfill({ contentType: 'text/javascript', body: '' });
    if (u.endsWith('firebase-config.js')) return r.fulfill({ contentType: 'text/javascript', body: 'const FIREBASE_CONFIG = { apiKey: "x", projectId: "test" };' });
    if (u.startsWith('http://localhost')) return r.continue(); return r.abort(); });
  const p = await ctx.newPage(); p.on('pageerror', e => errs.push(e.message));
  await p.goto('http://localhost:8765/importer.html');
  await p.evaluate(d => { localStorage.clear(); localStorage.setItem('__fakefs', JSON.stringify(d)); localStorage.setItem('jumeau-profil', 'p_a'); localStorage.setItem('jumeau-profil-nom', 'Armand Charrin'); }, data);
  await p.goto('http://localhost:8765/'); await p.waitForTimeout(1000);
  await p.click('#tabVis'); await p.waitForTimeout(300);
  console.log('puces :', await p.locator('.vventes:not(.sous) .vchip').allTextContents());
  await p.click('.vchip:has-text("Ventes passées")'); await p.waitForTimeout(300);
  console.log('sous :', await p.locator('.vventes.sous .vchip').allTextContents(), '| visites :', await p.locator('.vitem b').allTextContents());
  await p.click('.vventes.sous .vchip:has-text("Juin")'); await p.waitForTimeout(300);
  await p.screenshot({ path: '/tmp/passees.png' });
  console.log('tête :', await p.textContent('.vente-tete .eyebrow'), errs); await b.close();
})();
